package com.sneha.basics;

public class RelationalOperators {
    static void main() {
        System.out.println(53<4);
        System.out.println(5>4);
        System.out.println(53>=4);
        System.out.println(53!=4);
        System.out.println(7==4);      // equality operator
        System.out.println(10+5==15);

        boolean x =(5>2);
        System.out.println(x);

    }
}
