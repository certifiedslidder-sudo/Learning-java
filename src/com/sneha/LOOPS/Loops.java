package com.sneha.LOOPS;
//    print numbers from one to five

public class Loops {
    static void main() {
        /*
        SYNTAX OF FOR LOOPS:

        for(initialization; condition ; increment/decrement) {
            //body
           }

         */
    for(int num =1;num<=5;num++){
        System.out.println(num);

    }
    }
}
